package Basics_Java.Operators;

public class Theory {
    //Java me Operators wo special symbols hote hain jinka use variables aur values par alag-alag tarah ke operations (calculations, comparison, ya logic) perform karne ke liye kiya jata hai.
    //Java me operators ko main 7 groups me divide kiya gaya hai:
    //
    //1. Arithmetic Operators (अंकगणितीय ऑपरेटर्स)
    //
    //Inka use basic maths calculations ke liye hota hai:
    //• + (Addition): Do values ko jodta hai (e.g., 10 + 5 = 15). Iska use do Strings ko jodne ke liye bhi hota hai.
    //• - (Subtraction): Ek value me se dusri ko ghatata hai (e.g., 10 - 5 = 5).
    //• * (Multiplication): Do values ko multiply karta hai (e.g., 10 * 5 = 50).
    //• / (Division): Ek value ko dusri se bhag dekar bhagfal (Quotient) deta hai (e.g., 10 / 5 = 2).
    //• % (Modulus): Bhag dene ke baad jo sheshfal (Remainder) bachta hai, wo deta hai (e.g., 10 % 3 = 1).
    //
    //2. Assignment Operators
    //
    //Inka use variables me value store (assign) karne ke liye hota hai:
    //• =: Simple assignment (e.g., int x = 10;).
    //• Compound Assignments: Ye maths aur assignment ko mix karte hain:
    //	• += (e.g., x += 5 matlab x = x + 5)
    //	• -= (e.g., x -= 5 matlab x = x - 5)
    //	• *=, /=, %=
    //
    //3. Comparison / Relational Operators
    //
    //Ye do values ko compare karte hain aur answer hamesha true ya false (boolean) me dete hain:
    //• ==: Equal to (kya dono barabar hain?)
    //• !=: Not equal to (kya dono barabar nahi hain?)
    //• >: Greater than (bada hai)
    //• <: Less than (chota hai)
    //• >=: Greater than or equal to (bada ya barabar hai)
    //• <=: Less than or equal to (chota ya barabar hai)
    //
    //4. Logical Operators
    //
    //Inka use do ya do se zyada conditions ko aapas me jodne ke liye hota hai:
    //• && (Logical AND): Agar dono conditions sahi (true) hain, tabhi result true aayega.
    //• || (Logical OR): Agar dono me se koi EK bhi condition sahi hai, to result true aayega.
    //• ! (Logical NOT): Ye result ko ulta kar deta hai (true ko false aur false ko true).
    //
    //5. Unary Operators
    //
    //Inhe kaam karne ke liye sirf ek hi variable (operand) ki zaroorat hoti hai:
    //• ++ (Increment): Value ko 1 se badha deta hai (e.g., x++ ya ++x).
    //• -- (Decrement): Value ko 1 se ghata deta hai (e.g., x-- ya --x).
    //
    //6. Ternary Operator (? :)
    //
    //Ye if-else condition ka ek chota shorthand roop hai. Isme teen parts hote hain:
    //java
    //variable = (condition) ? expressionIfTrue : expressionIfFalse;
    //कोड का इस्तेमाल सावधानी से करें.
    //Agar condition true hai to pehli value milegi, nahi to dusri.
    //
    //7. Bitwise & Shift Operators
    //
    //Ye operators data ke bits (0 aur 1) par directly kaam karte hain (mostly advance programming me use hote hain):
    //• & (Bitwise AND), | (Bitwise OR), ^ (Bitwise XOR), ~ (Bitwise Complement).
    //• Shift Operators: << (Left shift), >> (Right shift), >>> (Unsigned right shift).
    //
    //Operator Precedence (Kaunsa pehle chalega?)
    //
    //Agar ek hi line me bohot saare operators hain, to Java is order me unhe solve karta hai:
    //1. Sabse pehle Brackets () ka code solve hoga.
    //2. Fir Unary operators (++, --).
    //3. Fir Multiply, Divide aur Modulus (*, /, %).
    //4. Fir Plus aur Minus (+, -).

}
